const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const { deriveBuildCapabilities } = require("../src/build-capabilities.cjs");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "src", "build-info.cjs");

function gitValue(args) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim() || "unknown";
  } catch {
    return "unknown";
  }
}

const packageInfo = require(path.join(root, "package.json"));
const ciCommit = String(process.env.GITHUB_SHA || "").trim();
const commit = ciCommit || gitValue(["rev-parse", "HEAD"]);
const dirty = ciCommit ? false : gitValue(["status", "--porcelain"]) !== "unknown" && gitValue(["status", "--porcelain"]) !== "";
const builtAt = new Date().toISOString();
const derived = deriveBuildCapabilities();
const info = {
  version: packageInfo.version,
  commit,
  dirty,
  builtAt,
  sourceMode: false,
  rendererProfileGeneration: derived.rendererProfileGeneration,
  capabilities: [...derived.capabilities],
  topologyCompilers: derived.topologyCompilers,
  semanticCompilers: derived.semanticCompilers,
};

fs.writeFileSync(
  outputPath,
  `// Generated by scripts/prepare-build-info.cjs during packaging.\nmodule.exports = Object.freeze(${JSON.stringify(info, null, 2)});\n`,
);
console.log(
  `Prepared build provenance for ${info.version} (${info.commit}${info.dirty ? ", dirty" : ""}).`,
);
