const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "src", "build-info.cjs");

function gitValue(args) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim() || "unknown";
  } catch {
    return "unknown";
  }
}

const packageInfo = require(path.join(root, "package.json"));
const commit = process.env.GITHUB_SHA || gitValue(["rev-parse", "--short=12", "HEAD"]);
const builtAt = new Date().toISOString();
const info = {
  version: packageInfo.version,
  commit,
  builtAt,
  sourceMode: false,
  rendererProfileGeneration: "toaster-raster-1",
  capabilities: [
    "labProposalInfluenceToggle",
    "deliveryProfile",
    "boundedFieldEnvelopeV1",
    "visualLanguageV2",
  ],
};

fs.writeFileSync(
  outputPath,
  `// Generated by scripts/prepare-build-info.cjs during packaging.\nmodule.exports = Object.freeze(${JSON.stringify(info, null, 2)});\n`,
);
console.log(`Prepared build provenance for ${info.version} (${info.commit}).`);
